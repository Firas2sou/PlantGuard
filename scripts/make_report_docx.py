#!/usr/bin/env python
"""Build the dataset-preparation report (DOCX) from reports/dataset_stats.json.

Run with the DSH bundled Python (has python-docx):
    "<bundled-python>" scripts/make_report_docx.py
"""
from __future__ import annotations

import json
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor

ROOT = Path(r"C:\plant-doctor")
REP = ROOT / "reports"

GRAY = RGBColor(0x59, 0x59, 0x59)
BLUE = RGBColor(0x1F, 0x4E, 0x79)


def h1(doc, text):
    doc.add_heading(text, level=1)


def h2(doc, text):
    doc.add_heading(text, level=2)


def p(doc, text, italic=False, size=None):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.italic = italic
    if size:
        run.font.size = Pt(size)
    return par


def bullets(doc, items):
    for it in items:
        doc.add_paragraph(it, style="List Bullet")


def table(doc, headers, rows, col_widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    for i, htext in enumerate(headers):
        cell = t.rows[0].cells[i]
        run = cell.paragraphs[0].add_run(htext)
        run.bold = True
        run.font.size = Pt(9.5)
    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            run = cells[i].paragraphs[0].add_run(str(value))
            run.font.size = Pt(9.5)
    if col_widths:
        for i, w in enumerate(col_widths):
            for row in t.rows:
                row.cells[i].width = Inches(w)
    return t


def code(doc, text):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.font.name = "Consolas"
    run.font.size = Pt(8.5)
    par.paragraph_format.space_after = Pt(6)
    return par


def caption(doc, text):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.italic = True
    run.font.size = Pt(9)
    run.font.color.rgb = GRAY
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER


def main() -> None:
    stats = json.loads((REP / "dataset_stats.json").read_text(encoding="utf-8"))

    doc = Document()
    doc.core_properties.title = "Plant Leaf Disease Classification - Project Report"
    doc.core_properties.subject = "Academic project - data, models and web application"

    # ---- title block ----
    title = doc.add_heading("Plant Leaf Disease Classification", level=0)
    for run in title.runs:
        run.font.color.rgb = BLUE
    p(doc, "Project Report - Data, Models and Web Application", size=14)
    p(doc, "Prepared 2 November 2026   |   Dataset: PlantVillage (Hughes & Salathe, 2015)",
      italic=True, size=10)
    p(doc, "All statistics in this document are generated by the project scripts listed in "
           "Section 8, so every number can be reproduced.", size=9)

    # ---- 1. overview ----
    h1(doc, "1. Project overview")
    p(doc, "The project builds a web application that tells the user, from a photograph of a leaf, "
           "whether the plant is healthy or diseased and, if diseased, which disease is the most "
           "likely. The classifier covers 38 classes - 26 diseases plus the healthy class of each "
           "crop - across 14 crop species.")
    p(doc, "This report documents the preparation phase: acquisition, extraction, splitting and "
           "quality audit, then the models trained on the resulting data and the web application "
           "that serves them. All three are complete; only optional validation on real "
           "photographs remains (Section 11).")

    # ---- 2. data source ----
    h1(doc, "2. Data source")
    p(doc, "The dataset is PlantVillage, an open repository of leaf images introduced in "
           "Mohanty et al. (2016) and first described by Hughes & Salathe (2015). Two mirrors were "
           "considered:")
    bullets(doc, [
        "Kaggle mirror (abdallahalidev/plantvillage-dataset): 2.18 GB, license CC BY-NC-SA 4.0.",
        "Hugging Face mirror (mohanty/PlantVillage): same images, license cc-by-sa-3.0, and it "
        "ships the official leaf-aware train/test split plus a leaf map (leaf_id per image).",
    ])
    p(doc, "The Hugging Face mirror was selected because its official split keeps all photographs "
           "of the same leaf inside one split, which prevents train/test leakage (verified in "
           "Section 5).")
    p(doc, "The archive contains three variants of the same 54,305 leaf photographs: color, "
           "grayscale and background-segmented (leaf on black background). Images are 256x256 "
           "JPEG, one centered leaf per image under laboratory conditions (uniform background, "
           "even lighting).")
    p(doc, "Known limitation: because the images are laboratory shots, a model trained only on "
           "this data learns shortcuts such as the uniform background. The original authors "
           "reported 99.35% accuracy on this dataset but only 31.4% on photographs taken in real "
           "field conditions (Mohanty et al., 2016). Robustness to real photographs is therefore "
           "a planned experiment of this project (Section 10), not an afterthought.")

    # ---- 3. pipeline ----
    h1(doc, "3. Preparation pipeline")
    table(doc,
          ["Step", "Script", "What it does"],
          [
              ["1. Download", "scripts/download_data.py",
               "Downloads data.zip (2,184,723,441 bytes), the six split manifests "
               "(color/grayscale/segmented x train/test) and leaf-map.json."],
              ["2. Extract", "scripts/prepare_data.py",
               "Extracts 163,034 archive entries into data/raw/plantvillage_hf/raw/<variant>/<class>/<image>."],
              ["3. Split", "scripts/prepare_data.py",
               "Keeps the official leaf-aware 80/20 split (43,596 train / 10,709 test), carves a "
               "stratified 10% validation set out of train (seed 42) and writes CSV manifests "
               "train/val/test with per-image label, crop and disease."],
              ["4. Audit", "scripts/audit_dataset.py",
               "Checks class count, image dimensions, corrupt files, exact and near duplicates "
               "(dHash), and whether any duplicate crosses a split boundary."],
          ],
          col_widths=[0.9, 1.9, 3.9])

    # ---- 4. statistics ----
    h1(doc, "4. Dataset statistics")
    h2(doc, "4.1 Variants")
    v = stats["variants"]
    table(doc, ["Variant", "Images", "Classes"],
          [[name, f"{d['images']:,}", d["classes"]] for name, d in v.items()],
          col_widths=[1.5, 1.2, 1.0])

    h2(doc, "4.2 Splits (color variant)")
    table(doc, ["Split", "Images", "Origin"],
          [
              ["train", f"{stats['split_sizes']['train']:,}",
               "Official leaf-aware train minus the 10% validation carve-out"],
              ["val", f"{stats['split_sizes']['val']:,}",
               "Stratified 10% of the official train (seed 42), used for model selection"],
              ["test", f"{stats['split_sizes']['test']:,}",
               "Official leaf-aware test, never touched during development"],
          ],
          col_widths=[0.9, 1.0, 4.3])
    p(doc, "No image path appears in more than one split.", italic=True, size=9)

    h2(doc, "4.3 Class balance")
    b = stats["balance"]
    p(doc, f"Class sizes are imbalanced: in train, from {b['train_min'][1]:,} images "
           f"({b['train_min'][0]}) to {b['train_max'][1]:,} images ({b['train_max'][0]}); in test, "
           f"from {b['test_min'][1]:,} ({b['test_min'][0]}) to {b['test_max'][1]:,} "
           f"({b['test_max'][0]}). Training therefore uses a class-weighted loss and reports "
           "macro-F1 alongside accuracy.")

    h2(doc, "4.4 Crops")
    rows = [
        [c["crop"], c["classes"], f"{c['train']:,}", f"{c['val']:,}", f"{c['test']:,}"]
        for c in stats["crops"]
    ]
    rows.append(["Total", stats["n_classes"],
                 f"{stats['split_sizes']['train']:,}",
                 f"{stats['split_sizes']['val']:,}",
                 f"{stats['split_sizes']['test']:,}"])
    table(doc, ["Crop", "Classes", "Train", "Val", "Test"], rows,
          col_widths=[2.2, 0.8, 0.9, 0.8, 0.9])

    chart = REP / "class_distribution.png"
    if chart.is_file():
        doc.add_paragraph().add_run().add_picture(str(chart), width=Inches(5.6))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        caption(doc, "Figure 1: images per class across train+validation (blue) and test (orange).")

    # ---- 5. audit ----
    h1(doc, "5. Quality audit")
    d = stats["duplicates"]
    table(doc, ["Check", "Result"],
          [
              ["Images scanned (color)", f"{stats['total_images']:,}"],
              ["Classes found / expected", f"{stats['n_classes']} / 38"],
              ["Corrupt or unreadable files", "0"],
              ["Image size", "All 256 x 256"],
              ["Exact duplicate groups", d["exact_groups"]],
              ["Near-duplicate pairs (dHash, Hamming <= 6)", d["near_pairs"]],
              ["Duplicates crossing a split boundary", f"{d['cross_split_exact'] + d['cross_split_near']} "
               f"({d['cross_split_exact']} exact, {d['cross_split_near']} near)"],
          ],
          col_widths=[3.4, 1.6])
    p(doc, "The near duplicates are different photographs of the same leaf, which is expected for "
           "this dataset. The important result is the last row: the official split is leaf-disjoint, "
           "so accuracy reported on the test set is not inflated by the same leaf appearing in both "
           "train and test.")

    # ---- 6. models ----
    h1(doc, "6. Models used and validation results")
    p(doc, "Two models were used, both built on MobileNetV3-Small, a lightweight convolutional "
           "network designed for mobile devices (Howard et al., 2019), pretrained on ImageNet. "
           "Input images are resized to 224x224.")
    table(doc, ["Model", "Role", "Trainable parameters", "Test top-1", "Test top-3", "Test macro-F1"],
          [
              ["Linear probe on frozen MobileNetV3-Small features (logistic regression)",
               "Baseline", "21,926", "97.26%", "99.88%", "96.51%"],
              ["MobileNetV3-Small, fine-tuned end-to-end (10 epochs, Radeon RX 9070)",
               "Main model", "1,556,806", "99.33%", "99.97%", "99.11%"],
          ],
          col_widths=[2.6, 0.8, 1.0, 0.8, 0.8, 0.9])
    p(doc, "The main model is exported to ONNX (opset 17, numerical parity verified) and is the "
           "model served by the web application. The high in-distribution accuracy confirms that "
           "the labels and the splits are coherent.")

    # ---- 7. application ----
    h1(doc, "7. Web application")
    p(doc, "The trained model is served by a small web application. A FastAPI server "
           "(src/serve/app.py) loads the ONNX model and exposes the endpoints below; a single "
           "static page (web/index.html) provides the user interface. No build toolchain is "
           "required - no Node.js, no bundler.")
    table(doc, ["Endpoint", "Purpose"],
          [
              ["GET /", "Single-page interface: camera or file upload, top-3 predictions, disease card"],
              ["GET /health", "Model name and number of classes (readiness check)"],
              ["POST /predict", "multipart image -> top-3 predictions with confidence and disease details"],
          ],
          col_widths=[1.3, 4.4])
    p(doc, "An uploaded photograph is resized so that its short side measures 256 pixels, "
           "centre-cropped to 224x224 and normalised with ImageNet statistics - exactly the "
           "pre-processing used at training time. The ONNX session returns the logits, a softmax "
           "gives the class probabilities, and the top three are returned together with a disease "
           "record from knowledge/diseases.json (crop, pathogen, symptoms, treatment, prevention).")
    p(doc, "A confidence gate prevents the application from guessing: if the best probability is "
           "below 0.60, or if its margin over the runner-up is below 0.15, the response is marked "
           "as not confident and the interface shows 'Not sure' instead of a disease name.")
    p(doc, "Verification: on a random sample of 300 test images, pre-processing through the API "
           "followed by ONNX inference gives 298 correct predictions (99.3%), identical to the "
           "accuracy measured at training time. Two manual checks returned Apple scab at 92.8% and "
           "tomato late blight at 82.8%.")
    code(doc, ".venv\\Scripts\\python.exe -m uvicorn src.serve.app:app --host 127.0.0.1 --port 8010")

    # ---- 8. reproducibility ----
    h1(doc, "8. Reproducibility")
    p(doc, "Environment: Windows 11, Python 3.12, AMD Ryzen 5 7500F (6 cores / 12 threads), "
           "32 GB RAM, AMD Radeon RX 9070. Training uses AMD's ROCm PyTorch build for Windows "
           "(torch 2.9.1+rocm7.2.1). Random seed 42 everywhere. The split manifests are frozen CSV "
           "files, so every experiment uses identical data.")
    code(doc,
         "python scripts/download_data.py --source hf --dest data/raw/plantvillage_hf\n"
         "python scripts/prepare_data.py\n"
         "python scripts/audit_dataset.py --data-dir data/raw/plantvillage_hf --out-dir reports \\\n"
         "    --variant color --splits-dir data/processed\n"
         "python scripts/e1_linear_probe.py\n"
         ".venv-rocm\\Scripts\\python.exe scripts/e2_finetune.py --epochs 10 --batch-size 128 --workers 12")

    # ---- 9. files ----
    h1(doc, "9. Files produced")
    table(doc, ["Path", "Contents"],
          [
              ["data/processed/train.csv, val.csv, test.csv", "Frozen split manifests (path, label, crop, disease)"],
              ["data/processed/class_index.json", "38 class names -> indices"],
              ["data/processed/split_summary.md", "Per-class counts per split"],
              ["reports/dataset_report.md", "Full audit report"],
              ["reports/class_counts.csv, duplicates.csv, near_duplicates.csv", "Raw audit outputs"],
              ["reports/dataset_stats.json, class_distribution.png", "Statistics and Figure 1"],
              ["reports/E1_linear_probe.md, E2_mobilenet_v3_small.md", "Validation experiment cards"],
              ["scripts/download_data.py, prepare_data.py, audit_dataset.py", "Preparation pipeline"],
              ["scripts/e1_linear_probe.py, e2_finetune.py, export_model.py", "Training and export"],
              ["src/serve/app.py", "FastAPI service: /predict, /health, static page"],
              ["web/index.html", "Single-page user interface (camera or upload)"],
              ["knowledge/diseases.json", "38 disease records shown after a prediction"],
          ],
          col_widths=[3.3, 3.4])

    # ---- 10. references ----
    h1(doc, "10. References")
    bullets(doc, [
        "Hughes, D., & Salathe, M. (2015). An open access repository of images on plant health to "
        "enable the development of mobile disease diagnostics. arXiv:1511.08060.",
        "Mohanty, S. P., Hughes, D. P., & Salathe, M. (2016). Using deep learning for image-based "
        "plant disease detection. Frontiers in Plant Science, 7, 1419. "
        "https://doi.org/10.3389/fpls.2016.01419",
        "Howard, A., Sandler, M., Chu, G., et al. (2019). Searching for MobileNetV3. ICCV 2019. "
        "arXiv:1905.02244.",
        "Dataset (Hugging Face mirror): https://huggingface.co/datasets/mohanty/PlantVillage",
        "Dataset (Kaggle mirror): https://www.kaggle.com/datasets/abdallahalidev/plantvillage-dataset",
    ])

    # ---- 11. next steps ----
    h1(doc, "11. Next steps")
    bullets(doc, [
        "Optional: informal test on about 20 real field photographs to report the "
        "laboratory-to-field gap honestly.",
        "Optional: expose the service on the local network so the camera can be used from a phone.",
        "Optional: deploy to a free hosting service for a live demonstration during the defence.",
    ])

    out = REP / "Dataset_Preparation_Report.docx"
    doc.save(out)
    print("saved", out)


if __name__ == "__main__":
    main()
